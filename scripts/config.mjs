import console from 'node:console';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';
import { parseEnv } from 'node:util';
import { targets } from '../config/targets.mjs';

/**
 * One configuration source for the whole repository.
 *
 *   pnpm config:sync    config/.env → the .env file of every app and service
 *   pnpm config:check   validate config/.env and find outdated or edited files
 *   pnpm config:import  build config/.env once from the existing .env files
 *
 * config/targets.mjs decides which program receives which setting. Output names
 * variables and files, never values: these files contain test secrets.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceFile = resolve(root, 'config/.env');
const templateFile = resolve(root, 'config/.env.example');
const hashPrefix = '# content-sha256: ';

// Fragments of the example values. A placeholder carries no information, so
// replacing one is never reported as losing a value.
const placeholderPattern = /REPLACE|YOUR_|your-|\.example\b|replace_me/;

class ConfigError extends Error {}

function isPlaceholder(value) {
  return placeholderPattern.test(value);
}

function sha256(text) {
  return createHash('sha256').update(text).digest('hex');
}

/** Node's own parser, the same one behind `node --env-file`. */
function readEnvFile(file) {
  return existsSync(file) ? parseEnv(readFileSync(file, 'utf8')) : undefined;
}

function loadSource() {
  const source = readEnvFile(sourceFile);
  if (!source) {
    throw new ConfigError(
      'config/.env is missing. Copy config/.env.example to config/.env and fill it in, or run `pnpm config:import` once to build it from the existing .env files.',
    );
  }

  return source;
}

function sourceKeyOf(spec) {
  return typeof spec === 'string' ? spec : spec.source;
}

/** Every setting name that at least one program receives. */
function managedSourceKeys() {
  return new Set(
    targets.flatMap((target) =>
      Object.values(target.settings).map(sourceKeyOf),
    ),
  );
}

/** The values one program receives. Unset or empty settings are left out. */
function desiredValues(target, source) {
  const values = {};
  for (const [key, spec] of Object.entries(target.settings)) {
    const value = source[sourceKeyOf(spec)];
    if (value === undefined || value === '') {
      continue;
    }

    values[key] = typeof spec === 'string' ? value : spec.forward(value);
  }

  return values;
}

// Plain values stay unquoted. Anything else is single-quoted, which Node, Vite,
// and Expo all read literally. Values they would read differently stop the
// sync instead of reaching a program changed.
function formatValue(key, value) {
  if (/^[\w.:/@+,=%-]*$/.test(value)) {
    return value;
  }

  if (!value.includes("'") && !/[\r\n]/.test(value)) {
    return `'${value}'`;
  }

  throw new ConfigError(
    `${key} contains a single quote or a line break, which .env files cannot carry safely.`,
  );
}

function renderBody(values) {
  const lines = Object.entries(values).map(
    ([key, value]) => `${key}=${formatValue(key, value)}`,
  );
  const body = lines.length ? `${lines.join('\n')}\n` : '';

  // Read the result back with the same parser the programs use.
  const parsed = parseEnv(body);
  for (const [key, value] of Object.entries(values)) {
    if (parsed[key] !== value) {
      throw new ConfigError(
        `${key} would not survive the round trip through a .env file.`,
      );
    }
  }

  return body;
}

/**
 * The header records a hash of the body. If the body no longer matches it,
 * someone edited the generated file, and sync must not discard that silently.
 */
function renderTarget(target, values) {
  const body = renderBody(values);
  return [
    '# Generated by `pnpm config:sync` from config/.env. Do not edit this file;',
    '# change config/.env and sync again.',
    `# ${target.purpose}`,
    `${hashPrefix}${sha256(body)}`,
    body,
  ].join('\n');
}

/** generated (untouched since the last sync), edited, or legacy (hand-written). */
function generatedState(content) {
  const start = content.indexOf(hashPrefix);
  if (start === -1) {
    return 'legacy';
  }

  const end = content.indexOf('\n', start);
  const recorded = content.slice(start + hashPrefix.length, end);
  const body = content.slice(end + 1);
  return sha256(body) === recorded ? 'generated' : 'edited';
}

/**
 * What an overwrite would destroy. A value counts as lost only when it is real
 * (not empty, not a placeholder) and config/.env does not hold it either.
 */
function overwriteRisks(content, values, source) {
  const existing = parseEnv(content);
  const meaningful = (value) => value !== '' && !isPlaceholder(value);
  const lost = Object.keys(existing).filter(
    (key) =>
      !(key in values) &&
      meaningful(existing[key]) &&
      source[key] !== existing[key],
  );
  const changed = Object.keys(values).filter(
    (key) =>
      key in existing &&
      existing[key] !== values[key] &&
      meaningful(existing[key]),
  );
  const added = Object.keys(values).filter((key) => !(key in existing));
  return { lost, changed, added };
}

function validUrl(value, https = false) {
  try {
    const url = new URL(value);
    return https
      ? url.protocol === 'https:'
      : ['http:', 'https:'].includes(url.protocol);
  } catch {
    return false;
  }
}

/**
 * Catch the mistakes that otherwise surface later as a crash or a refund:
 * a provider enabled without its settings, a bare subscription ID, a live
 * Stripe key. Messages name settings only.
 */
function validate(source) {
  const errors = [];
  const warnings = [];
  const value = (key) => source[key] ?? '';
  const isSet = (key) => value(key) !== '';
  const requireSet = (keys, reason) => {
    for (const key of keys) {
      if (!isSet(key)) {
        errors.push(`${key} is required ${reason}.`);
      } else if (isPlaceholder(value(key))) {
        warnings.push(`${key} still has the example value.`);
      }
    }
  };

  const requireMatch = (key, test, rule) => {
    if (isSet(key) && !test(value(key))) {
      errors.push(`${key} ${rule}.`);
    }
  };

  const requireFile = (key) => {
    if (isSet(key) && !isPlaceholder(value(key)) && !existsSync(value(key))) {
      errors.push(`${key} points to a file that does not exist.`);
    }
  };

  const managed = managedSourceKeys();
  for (const key of Object.keys(source)) {
    if (!managed.has(key)) {
      warnings.push(
        `${key} is not used by any program (check config/targets.mjs or the spelling).`,
      );
    }

    if (key.endsWith('_ENABLED') && !['true', 'false'].includes(value(key))) {
      errors.push(`${key} must be true or false.`);
    }
  }

  requireSet(['AUTH0_DOMAIN'], 'for every app and the API');
  // The audience is only an identifier. The guide's example value is a valid
  // choice that need not resolve, so it gets no placeholder warning.
  if (!isSet('AUTH0_AUDIENCE')) {
    errors.push('AUTH0_AUDIENCE is required for every app and the API.');
  }

  for (const key of ['WEB_AUTH0_CLIENT_ID', 'MOBILE_AUTH0_CLIENT_ID']) {
    if (isPlaceholder(value(key))) {
      warnings.push(`${key} still has the example value.`);
    }
  }

  requireMatch(
    'AUTH0_DOMAIN',
    (domain) => /^[a-zA-Z0-9.-]+$/.test(domain),
    'must be a bare domain, without https:// or a path',
  );
  requireMatch(
    'STRIPE_SECRET_KEY',
    (key) => /^(sk|rk)_test_/.test(key),
    'must be a Stripe test-mode key (sk_test_ or rk_test_)',
  );
  // A simple passphrase is fine for a local demo; only hint at the LAN risk.
  requireMatch(
    'ADMIN_SECRET',
    (secret) => secret.trim() === secret,
    'must not start or end with whitespace',
  );
  if (isSet('ADMIN_SECRET') && value('ADMIN_SECRET').length < 16) {
    warnings.push(
      'ADMIN_SECRET is short: fine on loopback, guessable while the API listens on the LAN. A long one: `openssl rand -base64 32`.',
    );
  }

  for (const key of ['WEB_ORIGIN', 'WEB_API_URL', 'MOBILE_API_URL']) {
    requireMatch(key, (url) => validUrl(url), 'must be an http or https URL');
  }

  if (value('APPLE_ENABLED') === 'true') {
    requireSet(
      [
        'APPLE_BUNDLE_ID',
        'APPLE_PRODUCT_ID',
        'APPLE_IAP_KEY_ID',
        'APPLE_IAP_ISSUER_ID',
        'APPLE_IAP_PRIVATE_KEY_PATH',
      ],
      'while APPLE_ENABLED=true',
    );
    requireFile('APPLE_IAP_PRIVATE_KEY_PATH');
  }

  if (value('GOOGLE_PLAY_ENABLED') === 'true') {
    requireSet(
      [
        'GOOGLE_PLAY_PACKAGE_NAME',
        'GOOGLE_PLAY_PRODUCT_ID',
        'GOOGLE_PLAY_BASE_PLAN_ID',
        'GOOGLE_PLAY_SERVICE_ACCOUNT_FILE',
        'GOOGLE_PLAY_PUSH_AUDIENCE',
        'GOOGLE_PLAY_PUSH_SERVICE_ACCOUNT_EMAIL',
        'GOOGLE_PLAY_PUSH_SUBSCRIPTION',
      ],
      'while GOOGLE_PLAY_ENABLED=true',
    );
    requireFile('GOOGLE_PLAY_SERVICE_ACCOUNT_FILE');
  }

  if (value('CLOUD_GOOGLE_PLAY_ENABLED') === 'true') {
    requireSet(
      [
        'GOOGLE_PLAY_SECRET_ARN',
        'CLOUD_GOOGLE_PLAY_PUSH_AUDIENCE',
        'CLOUD_GOOGLE_PLAY_PUSH_SUBSCRIPTION',
      ],
      'while CLOUD_GOOGLE_PLAY_ENABLED=true',
    );
  }

  requireMatch(
    'GOOGLE_PLAY_PACKAGE_NAME',
    (name) => /^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+$/.test(name),
    'must be an Android package name such as com.yourcompany.app',
  );
  for (const key of [
    'GOOGLE_PLAY_PUSH_AUDIENCE',
    'CLOUD_GOOGLE_PLAY_PUSH_AUDIENCE',
  ]) {
    requireMatch(key, (url) => validUrl(url, true), 'must be an HTTPS URL');
  }

  for (const key of [
    'GOOGLE_PLAY_PUSH_SUBSCRIPTION',
    'CLOUD_GOOGLE_PLAY_PUSH_SUBSCRIPTION',
  ]) {
    requireMatch(
      key,
      (name) => /^projects\/[^/]+\/subscriptions\/[^/]+$/.test(name),
      'must be the full name projects/<project-id>/subscriptions/<subscription-id>, not just the ID',
    );
  }

  if (isSet('ANDROID_UPLOAD_KEYSTORE_FILE')) {
    requireFile('ANDROID_UPLOAD_KEYSTORE_FILE');
  }

  return { errors, warnings };
}

function printFindings({ errors, warnings }) {
  for (const warning of warnings) {
    console.warn(`  warning  ${warning}`);
  }

  for (const error of errors) {
    console.error(`  error    ${error}`);
  }
}

function sync({ force }) {
  const source = loadSource();
  const findings = validate(source);
  printFindings(findings);
  if (findings.errors.length) {
    // Writing a known-broken configuration would only move the failure into
    // a running service, where it is harder to read.
    throw new ConfigError('config/.env has errors; no file was written.');
  }

  let blocked = 0;
  for (const target of targets) {
    const file = resolve(root, target.file);
    const values = desiredValues(target, source);
    const content = renderTarget(target, values);
    const current = existsSync(file) ? readFileSync(file, 'utf8') : undefined;

    if (current === content) {
      console.info(`  ok       ${target.file}`);
      continue;
    }

    let note = current === undefined ? 'created' : 'updated';
    const state = current === undefined ? 'generated' : generatedState(current);
    if (current !== undefined && state !== 'generated') {
      const { lost, changed, added } = overwriteRisks(current, values, source);
      if ((lost.length || changed.length) && !force) {
        blocked++;
        const origin =
          state === 'legacy'
            ? 'written by hand before config:sync'
            : 'edited by hand since the last sync';
        console.error(
          `  kept     ${target.file}: ${origin}. These values differ from config/.env: ${[...lost, ...changed].join(', ')}. Put the right values into config/.env, then sync again; --force overwrites this file.`,
        );
        continue;
      }

      note = added.length ? `adopted, adds ${added.join(', ')}` : 'adopted';
    }

    // New files are readable by the owner only; they can hold test secrets.
    writeFileSync(file, content, { mode: 0o600 });
    console.info(`  ${note.padEnd(8)} ${target.file}`);
  }

  if (blocked) {
    throw new ConfigError(`${blocked} file(s) were kept; see above.`);
  }
}

function check() {
  const source = loadSource();
  const findings = validate(source);
  printFindings(findings);

  let stale = 0;
  for (const target of targets) {
    const file = resolve(root, target.file);
    const content = renderTarget(target, desiredValues(target, source));
    const current = existsSync(file) ? readFileSync(file, 'utf8') : undefined;
    let status = 'ok';
    if (current === undefined) {
      status = 'missing: run pnpm config:sync';
    } else if (current !== content) {
      const state = generatedState(current);
      status =
        state === 'edited'
          ? 'edited by hand: move the change into config/.env'
          : state === 'legacy'
            ? 'not generated yet: run pnpm config:sync'
            : 'out of date: run pnpm config:sync';
    }

    if (status !== 'ok') {
      stale++;
    }

    console.info(
      `  ${status === 'ok' ? 'ok      ' : 'stale   '} ${target.file}${status === 'ok' ? '' : `  (${status})`}`,
    );
  }

  if (findings.errors.length || stale) {
    throw new ConfigError('Configuration needs attention; see above.');
  }

  console.info('Configuration is valid and every generated file is current.');
}

/** Collect every value the existing files hold for each setting. */
function collectExisting() {
  const managed = managedSourceKeys();
  const candidates = new Map();
  const unmanaged = [];
  const add = (sourceKey, file, value) => {
    if (value === '') {
      return;
    }

    const list = candidates.get(sourceKey) ?? [];
    list.push({ file, value });
    candidates.set(sourceKey, list);
  };

  for (const target of targets) {
    const existing = readEnvFile(resolve(root, target.file));
    if (!existing) {
      continue;
    }

    for (const [key, value] of Object.entries(existing)) {
      const spec = target.settings[key];
      if (spec) {
        add(
          sourceKeyOf(spec),
          target.file,
          typeof spec === 'string' ? value : spec.reverse(value),
        );
      } else {
        unmanaged.push(`${target.file}: ${key}`);
        // A leftover copy can still be the only place that holds a value.
        if (managed.has(key)) {
          add(key, target.file, value);
        }
      }
    }
  }

  return { candidates, unmanaged };
}

/**
 * Prefer real values over placeholders, then the value most files agree on.
 * Disagreements are reported by file, never by value.
 */
function chooseValues(candidates) {
  const chosen = {};
  const conflicts = [];
  for (const [key, list] of candidates) {
    const real = list.filter((candidate) => !isPlaceholder(candidate.value));
    const pool = real.length ? real : list;
    const counts = new Map();
    for (const { value } of pool) {
      counts.set(value, (counts.get(value) ?? 0) + 1);
    }

    const [winner] = [...counts.entries()].sort((a, b) => b[1] - a[1])[0];
    chosen[key] = winner;
    if (counts.size > 1) {
      const differing = pool
        .filter((candidate) => candidate.value !== winner)
        .map((candidate) => candidate.file);
      const agreeing = pool
        .filter((candidate) => candidate.value === winner)
        .map((candidate) => candidate.file);
      conflicts.push(
        `${key}: kept the value from ${agreeing.join(', ')}; ${differing.join(', ')} had a different one`,
      );
    }
  }

  return { chosen, conflicts };
}

function importExisting({ force }) {
  if (existsSync(sourceFile) && !force) {
    throw new ConfigError(
      'config/.env already exists. Edit it directly, or use --force to rebuild it from the .env files.',
    );
  }

  const { candidates, unmanaged } = collectExisting();
  const { chosen, conflicts } = chooseValues(candidates);

  // Fill the commented template, so config/.env keeps its explanations.
  const used = new Set();
  const lines = readFileSync(templateFile, 'utf8')
    .split('\n')
    .map((line) => {
      const match = /^(?:#\s*)?([A-Z][A-Z0-9_]*)=/.exec(line);
      const key = match?.[1];
      if (!key || !(key in chosen) || used.has(key)) {
        return line;
      }

      used.add(key);
      return `${key}=${formatValue(key, chosen[key])}`;
    });
  const extra = Object.keys(chosen).filter((key) => !used.has(key));
  if (extra.length) {
    lines.push(
      '# Imported settings that the template does not list yet.',
      ...extra.map((key) => `${key}=${formatValue(key, chosen[key])}`),
      '',
    );
  }

  writeFileSync(sourceFile, lines.join('\n'), { mode: 0o600 });
  console.info(
    `Wrote config/.env with ${Object.keys(chosen).length} settings from the existing .env files.`,
  );
  for (const conflict of conflicts) {
    console.warn(`  conflict ${conflict}`);
  }

  for (const entry of unmanaged) {
    console.warn(`  unused   ${entry} (not read by this program)`);
  }

  console.info(
    'Review config/.env (especially the conflicts above), then run `pnpm config:sync`.',
  );
}

const [command, ...flags] = process.argv.slice(2);
const options = { force: flags.includes('--force') };
const commands = { sync, check, import: importExisting };

try {
  if (!commands[command]) {
    throw new ConfigError(
      'Usage: node scripts/config.mjs <sync|check|import> [--force]',
    );
  }

  commands[command](options);
} catch (error) {
  if (!(error instanceof ConfigError)) {
    throw error;
  }

  console.error(error.message);
  process.exitCode = 1;
}
